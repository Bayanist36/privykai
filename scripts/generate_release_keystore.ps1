param(
    [string]$KeystorePath = '',
    [string]$Alias = 'habittracker',
    [string]$DistinguishedName = 'CN=Sukhanov labs, O=Sukhanov labs, C=RU',
    [int]$ValidityDays = 10000,
    [switch]$Force
)

. (Join-Path $PSScriptRoot 'common.ps1')

$projectRoot = Get-ProjectRoot
Initialize-AndroidEnvironment -ProjectRoot $projectRoot

if (-not $KeystorePath) {
    $KeystorePath = Join-Path $env:USERPROFILE '.sukhanovlabs\habittracker-release.jks'
}
$keystoreFullPath = [System.IO.Path]::GetFullPath($KeystorePath)

if ((Test-Path -LiteralPath $keystoreFullPath) -and -not $Force) {
    throw "Keystore already exists at $keystoreFullPath. Pass -Force to overwrite it."
}

$keytool = Join-Path $env:JAVA_HOME 'bin\keytool.exe'
if (-not (Test-Path -LiteralPath $keytool)) {
    $keytoolCommand = Get-Command keytool -ErrorAction SilentlyContinue
    if ($null -eq $keytoolCommand) {
        throw 'keytool was not found. Install a JDK 17+ and set JAVA_HOME.'
    }
    $keytool = $keytoolCommand.Source
}

function Read-PlainPassword {
    param([Parameter(Mandatory = $true)][string]$Prompt)

    $secure = Read-Host -Prompt $Prompt -AsSecureString
    $pointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try {
        return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($pointer)
    }
    finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($pointer)
    }
}

Write-Host 'Generating the company release keystore. Back up the file and the passwords.'
Write-Host "Keystore: $keystoreFullPath"
Write-Host "Alias:    $Alias"

$storePassword = Read-PlainPassword -Prompt 'New store password'
$confirmation = Read-PlainPassword -Prompt 'Repeat store password'
if ($storePassword -ne $confirmation) {
    throw 'Passwords do not match.'
}
if ([string]::IsNullOrWhiteSpace($storePassword)) {
    throw 'The store password must not be empty.'
}

$keystoreDirectory = Split-Path -Parent $keystoreFullPath
if ($keystoreDirectory) {
    New-Item -ItemType Directory -Path $keystoreDirectory -Force | Out-Null
}

& $keytool `
    -genkeypair -v `
    -keystore $keystoreFullPath `
    -storetype PKCS12 `
    -alias $Alias `
    -keyalg RSA `
    -keysize 4096 `
    -validity $ValidityDays `
    -storepass $storePassword `
    -keypass $storePassword `
    -dname $DistinguishedName

if ($LASTEXITCODE -ne 0) {
    throw "keytool failed with exit code $LASTEXITCODE."
}

$propertiesPath = Join-Path $projectRoot 'android\key.properties'
$gradleStorePath = $keystoreFullPath.Replace('\', '/')
$properties = @(
    '# Generated by scripts/generate_release_keystore.ps1.'
    '# Never commit this file: it contains the release password.'
    "storeFile=$gradleStorePath"
    "storePassword=$storePassword"
    "keyAlias=$Alias"
    "keyPassword=$storePassword"
)
Set-Content -LiteralPath $propertiesPath -Value $properties -Encoding utf8

Write-Host ''
Write-Host "Keystore:  $keystoreFullPath"
Write-Host "Signing:   $propertiesPath (git-ignored)"
Write-Host 'Next: run scripts/build_release_apk.ps1 to build and verify split APKs.'
Write-Host 'Keep an offline backup of the keystore: it is required for every update.'
