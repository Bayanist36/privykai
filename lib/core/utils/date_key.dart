/// Stable calendar-day keys used for persisted completion dates.
///
/// Stored as `yyyy-MM-dd` so the data stays readable and timezone-safe:
/// a completion always belongs to a calendar day, not to an instant.
abstract final class DateKey {
  static String from(DateTime dateTime) {
    final local = dateTime.toLocal();
    final month = local.month.toString().padLeft(2, '0');
    final day = local.day.toString().padLeft(2, '0');
    return '${local.year}-$month-$day';
  }

  static DateTime? parse(String value) {
    final parts = value.split('-');
    if (parts.length != 3) {
      return null;
    }
    final year = int.tryParse(parts[0]);
    final month = int.tryParse(parts[1]);
    final day = int.tryParse(parts[2]);
    if (year == null || month == null || day == null) {
      return null;
    }
    return DateTime(year, month, day);
  }
}
